// The share of taxpayers (0 to 100) with a before-tax income below `income`.
export function percentileOf(income: number): number {
  const rows = INCOME_PERCENTILES;
  if (income < rows[0][1]) return 0;
  const last = rows[rows.length - 1];
  if (income >= last[1]) return last[0];
  const i = rows.findIndex((row) => row[1] > income);
  const [p0, v0] = rows[i - 1];
  const [p1, v1] = rows[i];
  return p0 + ((income - v0) / (v1 - v0)) * (p1 - p0);
}
